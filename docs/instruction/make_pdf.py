S['tcm']  = ParagraphStyle('tcm', fontName='M', fontSize=8.6, leading=12.5, textColor=DARK)

F = []


def P(t, s='p'):
    # Каждая Часть — с новой страницы. Делается здесь, а не руками по тексту:
    # ручные разрывы разъезжаются при любой правке и оставляют пустые страницы.
    if s == 'h1' and t.startswith('Часть'):
        F.append(PageBreakIfNotEmpty())
    # Подзаголовок не должен остаться последней строкой страницы.
    if s == 'h2':
        F.append(CondPageBreak(35 * mm))
    F.append(Paragraph(t, S[s]))


def SP(h=3):
    F.append(Spacer(1, h * mm))


def step(num, title):
    """Синяя плашка с номером шага. Не оставляем её одну внизу страницы."""
    F.append(CondPageBreak(45 * mm))
    t = Table([[Paragraph(f"ШАГ {num}", S['step']), Paragraph(title, S['step'])]],
              colWidths=[22 * mm, CW - 22 * mm])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (0, 0), colors.HexColor("#0d4fa8")),
        ('BACKGROUND', (1, 0), (1, 0), BLUE),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 5), ('RIGHTPADDING', (0, 0), (-1, -1), 5),
        ('TOPPADDING', (0, 0), (-1, -1), 4), ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
    ]))
    F.append(Spacer(1, 5 * mm))
    F.append(t)
    F.append(Spacer(1, 3 * mm))


def box(kind, title, lines):
    """Цветная врезка: warn / ok / err."""
    bg, bd = {'warn': (WARNBG, WARNBD), 'ok': (OKBG, OKBD), 'err': (REDBG, REDBD)}[kind]
    inner = [Paragraph(f"<b>{title}</b>", S['p'])] if title else []
    for l in lines:
        inner.append(Paragraph(l, S['p']))
    t = Table([[inner]], colWidths=[CW])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), bg),
        ('LINEBEFORE', (0, 0), (0, -1), 2.5, bd),
        ('LEFTPADDING', (0, 0), (-1, -1), 7), ('RIGHTPADDING', (0, 0), (-1, -1), 7),
        ('TOPPADDING', (0, 0), (-1, -1), 6), ('BOTTOMPADDING', (0, 0), (-1, -1), 2),
    ]))
    F.append(t)
    F.append(Spacer(1, 3.5 * mm))


def code(lines):
    """Тёмный блок с кодом."""
    if isinstance(lines, str):
        lines = [lines]
    inner = [Paragraph(l.replace('&', '&amp;').replace(' ', '&nbsp;').replace('<', '&lt;').replace('>', '&gt;')
                       if l else '&nbsp;', S['code']) for l in lines]
    t = Table([[inner]], colWidths=[CW])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), CODEBG),
        ('LEFTPADDING', (0, 0), (-1, -1), 8), ('RIGHTPADDING', (0, 0), (-1, -1), 8),
        ('TOPPADDING', (0, 0), (-1, -1), 6), ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
    ]))
    F.append(t)
    F.append(Spacer(1, 3.5 * mm))


def shot(name, caption, maxw=CW, maxh=78 * mm):
    """Скриншот с подписью, вписанный в рамку."""
    from PIL import Image as PIL
    p = os.path.join(IMG, name + ".png")
    iw, ih = PIL.open(p).size
    sc = min(maxw / iw, maxh / ih)
    im = Image(p, iw * sc, ih * sc)
    im.hAlign = 'CENTER'
    F.append(KeepTogether([im, Paragraph(caption, S['cap'])]))


def table(rows, widths, header=True):
    data = []
    for i, r in enumerate(rows):
        data.append([Paragraph(c, S['tcb'] if (header and i == 0) else
                               (S['tcm'] if c.startswith('`') else S['tc'])).__class__ and
                     Paragraph(c.replace('`', ''), S['tcb'] if (header and i == 0)
                               else (S['tcm'] if c.startswith('`') else S['tc'])) for c in r])
    t = Table(data, colWidths=widths, repeatRows=1 if header else 0)
    st = [('VALIGN', (0, 0), (-1, -1), 'TOP'),
          ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#dcdfe3")),
          ('LEFTPADDING', (0, 0), (-1, -1), 5), ('RIGHTPADDING', (0, 0), (-1, -1), 5),
          ('TOPPADDING', (0, 0), (-1, -1), 4), ('BOTTOMPADDING', (0, 0), (-1, -1), 4)]
    if header:
        st.append(('BACKGROUND', (0, 0), (-1, 0), LIGHT))
    t.setStyle(TableStyle(st))
    F.append(t)
    F.append(Spacer(1, 4 * mm))


